import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

// Export source cells only. Profiling notebooks require a GPU and must never be
// executed as part of the documentation build; saved outputs are omitted too.
const notebookPath =
  "tutorials/jax-profiling/diagnose_compute_and_memory_bound_custom_jax_kernels.ipynb";
const root = new URL("../", import.meta.url);
const notebook = JSON.parse(readFileSync(new URL(notebookPath, root), "utf8"));
const output = new URL(notebookPath.replace(/\.ipynb$/, ".md"), root);
const github = "https://github.com/NVIDIA/JAX-Toolbox/blob/main/";
const sections = [
  "{/* Generated by npm run docs:export. Edit the notebook, then regenerate. */}",
  `[Open the notebook on GitHub](${github}${notebookPath}) · ` +
    `[Helper scripts](https://github.com/NVIDIA/JAX-Toolbox/tree/main/tutorials/jax-profiling/scripts) · ` +
    "[Setup instructions](README.md)",
];

for (const cell of notebook.cells) {
  const source = (Array.isArray(cell.source) ? cell.source.join("") : cell.source).trimEnd();
  if (!source) continue;
  if (Object.keys(cell.attachments ?? {}).length) {
    throw new Error("Notebook attachments must be moved to images/ before exporting.");
  }
  if (cell.cell_type === "markdown") {
    sections.push(source);
  } else if (cell.cell_type === "code") {
    // Longer fences keep literal backticks in Python strings inside the block.
    const longest = Math.max(0, ...(source.match(/`+/g) ?? []).map((run) => run.length));
    const fence = "`".repeat(Math.max(3, longest + 1));
    sections.push(`${fence}python\n${source}\n${fence}`);
  } else {
    throw new Error(`Unsupported notebook cell type: ${cell.cell_type}`);
  }
}

const markdown = sections.join("\n\n") + "\n";
if (process.argv.includes("--check")) {
  let current;
  try {
    current = readFileSync(output, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  if (current !== markdown) {
    console.error("Tutorial Markdown is missing or stale. Run npm run docs:export and commit the result.");
    process.exitCode = 1;
  } else {
    console.log("Tutorial Markdown is up to date.");
  }
} else {
  writeFileSync(output, markdown);
  console.log(`Exported ${fileURLToPath(output)}`);
}
